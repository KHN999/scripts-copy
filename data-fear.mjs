/**
 * This script is written in one-line beats and several of them are a single
 * connective. Under about fourteen characters the voice comes back
 * mispronounced or as nothing at all, so a fragment is folded into the line it
 * introduces; the pause comes from the beat between units instead.
 */
const MIN_UNIT = 14;
SCENES.forEach((s) => {
  const out = [];
  for (const u of s.u) {
    if (out.length && out[out.length - 1].length < MIN_UNIT) out[out.length - 1] += " " + u;
    else out.push(u);
  }
  while (out.length > 1 && out[out.length - 1].length < MIN_UNIT) out[out.length - 2] += " " + out.pop();
  s.u = out;
});

/** The three shots that happen after the night is over. */
const AT = { day: new Set([
  "The Body Did Nothing All Night", "Every Shout Came From the Living Son",
  "What I Remember Is Not the Ghosts"]) };

SCENES.forEach((s) => {
  s.cam = CAM[s.k];
  if (!s.cam) throw new Error(`shot "${s.t}" has no camera for k="${s.k}"`);
  s.time = s.k === "memory" || s.l === "အမေကြီးအိမ်" ? (s.k === "memory" ? TIME.memory : TIME.day)
    : s.k === "out" ? TIME.out
    : AT.day.has(s.t) ? TIME.day
    : TIME.night;

  let cont = CONT;
  if ((s.w ?? []).some((w) => DEAD.has(w))) cont += CONT_DEAD;
  if ((s.w ?? []).includes("ဦးမောင်ဝ")) cont += CONT_BODY;
  if ((s.w ?? []).includes("ကိုနေမင်း")) cont += CONT_NAY;
  s.cont = cont;
  s.style = STYLE;
});

