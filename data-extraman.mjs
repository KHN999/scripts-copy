SCENES.forEach((s) => {
  const out = [];
  for (const u of s.u) {
    if (out.length && out[out.length - 1].length < MIN_UNIT) out[out.length - 1] += " " + u;
    else out.push(u);
  }
  while (out.length > 1 && out[out.length - 1].length < MIN_UNIT) out[out.length - 2] += " " + out.pop();
  s.u = out;
});

/** Shots that carry the whole photograph-with-a-space rule. */
const PHOTO = new Set(["မိသားစုဓာတ်ပုံ"]);

SCENES.forEach((s) => {
  s.cam = CAM[s.k];
  if (!s.cam) throw new Error(`shot "${s.t}" has no camera for k="${s.k}"`);
  s.time = s.k === "mem" || s.k === "memlow" ? TIME.mem
    : s.tm ? TIME[s.tm]
    : TIME.night;

  let cont = CONT;
  if ((s.w ?? []).includes("မင်းခန့်")) cont += CONT_BOY;
  if ((s.w ?? []).includes("အမေ")) cont += CONT_MOTHER;
  if (s.empty) cont += CONT_EMPTY;
  if (s.photo) cont += CONT_PHOTO;
  s.cont = cont;
  s.style = STYLE;
});

export { CONT, STYLE, PHOTO };
