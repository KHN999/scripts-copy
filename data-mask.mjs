/**
 * မျက်နှာဖုံးနောက်က လူ — THE MAN BEHIND THE MASK.
 *
 * 2019, a Bago village. Aung Min's father is dead and his mother is ill, so
 * when a job comes up for his sister May Thi — three hundred thousand a month,
 * cooking and cleaning for U Ba Thein at the edge of the village — he lets her
 * take it, against his own judgement. U Ba Thein lives alone in a big timber
 * house with half his face burned away ten years ago and a cloth over it. The
 * children call him the ogre. A woman who worked for him once went missing.
 *
 * He gives May Thi three rules. Don't go behind the house after eight. Never
 * open the back room. If somebody calls you in the night, don't answer. And
 * then, quietly: my wife is in that room, she doesn't want to see people.
 *
 * Every night at eight he lays two plates, carries one to the brick room,
 * unlocks it, goes in, and comes out half an hour later.
 *
 * ⚠️ WHAT THE STORY IS ABOUT. The wife died ten years ago. She has been fed
 * every night since, by a man who would not leave her alone. The fire that
 * took his face was not an accident: Ma Khin Lay, jealous of a twenty-year-old
 * orphan housemaid called Sanda, pushed her into the kitchen fire and then
 * bolted the door on her from the outside and listened to her beat on it. U Ba
 * Thein knew, and loved his wife, and buried it for ten years — and that
 * buried truth, not his face, is the thing in the house worth being afraid of.
 *
 * ──────────────────────────────────────────────────────────────────────────
 *
 * FIVE RULES THIS BOARD IS BUILT ON.
 *
 * 1. ⚠️ EVERY BURN IN THIS FILM IS TEN YEARS HEALED. The script says the
 *    ghost's face has no skin and shows bone and teeth. Written down that way
 *    the prompt is refused, and when it is not refused the generator punches a
 *    crater through a head. What is drawn instead is what a decade-old burn
 *    actually is: skin that is smooth, tight, shiny and the wrong colour, a
 *    missing eyebrow, an eye-corner pulled out of line. Closed, dry, and
 *    nobody's idea of a wound.
 *
 * 2. ⚠️ ONLY ONE SIDE OF MA KHIN LAY IS EVER SHOWN. The ruined half the
 *    brother sees is the half this board refuses to draw — always turned away,
 *    in shadow, or outside the frame. This is the safe way to shoot it and it
 *    is also the better way: the audience finishes the face, and what they
 *    build is worse than anything a model would return.
 *
 * 3. ⚠️ NOBODY IS EVER SHOWN BURNING. The fire ten years ago is shown by what
 *    it leaves and where it is not — orange light under a shut door, smoke
 *    along a ceiling, a bolt thrown from the outside, soot on a wall. No flame
 *    touches a person in any frame of this film.
 *
 * 4. ⚠️ THE PLATE IS A LIVING WOMAN. Ma Khin Lay's reference is built as the
 *    village beauty she was, warm and unmarked, because the last shot of the
 *    film is her restored and that must be the SAME face. What is wrong with
 *    her is stated per shot and is never in the plate.
 *
 * 5. ⚠️ U BA THEIN IS NOT A MONSTER AND THE CAMERA KNOWS IT BEFORE WE DO. He
 *    is never lit from below, never shot from a low angle, never framed like a
 *    threat. The village is wrong about him and the pictures are on his side
 *    from the first frame.
 */

