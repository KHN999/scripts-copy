/**
 * အနောက်ဆောင်က ရေတောင်းသံ — THE SOUND OF SOMEONE ASKING FOR WATER. 107 shots.
 *
 * A boy's first night on palace watch. The west wing has been sealed for three
 * years and there is a woman inside it asking for water. The captain of the
 * watch tells him two things: keep the lamps lit, and whatever it says, do not
 * answer. The captain takes ill and leaves. The voice comes back.
 *
 * He gives her the water. A hand comes out under the door — a queen's hand,
 * gold and rubies at the wrist, the skin drawn dry over the bones — and it does
 * not take the cup. It takes him. When the captain returns and sees that
 * bracelet he goes down on his knees, and the voice stops being gentle.
 *
 * ⚠️ WHAT THE STORY IS ABOUT. She was shut in by the king's anger with an order
 * that she be given no food and no water. The man who carried out that order is
 * the captain, who sat outside for three days listening to her ask. The horror
 * is not that she is dead — it is that someone heard her for three days and
 * obeyed. The boy is the first person in three years to answer.
 *
 * ──────────────────────────────────────────────────────────────────────────
 *
 * FIVE RULES THIS BOARD IS BUILT ON.
 *
 * 1. ⚠️ THE PERIOD IS CARRIED IN THE MATERIALS, NOT IN A LABEL. "Konbaung" and
 *    "nineteenth century" mean little to a generator; lacquered teak, gold leaf
 *    lifting at the edges, luntaya acheik silk, a gaung baung, an earthenware
 *    oil lamp with a cotton wick — those build the room. Every reference names
 *    what a thing is MADE OF and every shot names the light falling on it.
 *
 * 2. ⚠️ THE QUEEN IS SHOWN IN THREE STAGES AND NEVER ALL AT ONCE UNTIL SHOT 78.
 *    A hand under the door (42), a face at a gap four inches off the floor
 *    (48), and only then the whole of her on the bed. Before shot 42 the sealed
 *    wing is a closed door and a sound. Putting her in early spends the only
 *    card the film has.
 *
 * 3. ⚠️ SHE IS A PERSON, PHOTOGRAPHED AS A PERSON. Very thin, the cheeks fallen
 *    in, the lips dry and split, the skin drawn tight and dull over the bones
 *    of the hands and face — the look of a body that has dried rather than
 *    decayed. Her silk has not faded and her gold is still bright, and that
 *    contrast is the whole image. No wounds, no blood, no exposed bone, no
 *    rotting: those belong to a different film and they would make her the
 *    villain, which she is not.
 *
 * 4. ⚠️ THE INSIDE OF THE WING IS BLACK UNTIL THE DOORS COME OFF. Every shot at
 *    the door shows the gap, the boards, the iron, the lamplight dying a foot
 *    inside — and nothing beyond it. The audience must not get a free look.
 *    When she opens her mouth at the gap the inside of it is simply unlit, a
 *    flat dark with no light reaching in; the narration says what is missing
 *    and the picture does not have to.
 *
 * 5. ⚠️ THREE LAMPS, AND THEY ARE THE ONLY LIGHT. The corridor runs away into
 *    real dark. Shots are lit by one small warm flame at a known distance, so
 *    faces are half-lit and the far door is barely resolved. The one exception
 *    is the morning, which is flat grey daylight and merciless.
 */

