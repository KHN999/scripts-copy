/**
 * ၇၉ ချပ်မြောက်ကတ် — THE SEVENTY-NINTH CARD. 91 shots.
 *
 * Lin Htet, thirty, goes to a tarot reader a friend recommended. She looks at
 * the first card, then at the empty chair beside him, and says he did not come
 * alone. The third card has another card stuck underneath it — one that is not
 * in her deck and never has been. She has used these cards for twelve years and
 * knows all seventy-eight. This is the seventy-ninth.
 *
 * It shows a door with two children at it, one outside and one in, and the word
 * THE OTHER. The friend turns out never to have recommended her; the message on
 * Lin Htet's phone does not exist on anybody else's. And his mother, asked
 * whether he had a brother, drops a cup.
 *
 * ⚠️ WHAT THE STORY IS ABOUT. He was a twin. At seven both boys took a fever,
 * and in the morning one was gone from a locked room — and the one left behind
 * could not remember his own name. They were identical and unmarked, so nobody
 * could tell which boy had been lost. The father simply decided the survivor was
 * Lin Htet, and that is who he has been for twenty-three years. The horror is
 * not that his brother is missing. It is that he does not know which of them he
 * is, and that there turns out to have been a third voice in the room.
 *
 * ──────────────────────────────────────────────────────────────────────────
 *
 * FIVE RULES THIS BOARD IS BUILT ON.
 *
 * 1. ⚠️ THE CHILD'S FACE IS NOT SEEN UNTIL SHOT 71 OF 91. In the dream he is a hand
 *    being held, a shape at the end of a road, a voice. The whole film turns on
 *    one moment of recognition — the face is Lin Het's own at seven — and that
 *    only lands if the audience has been denied it for seventy shots.
 *
 * 2. ⚠️ EVERY TAROT CARD IN THIS FILM IS THE SAME DECK. Flat medieval-style
 *    illustration, heavy black outline, a narrow palette of yellow, blue, red
 *    and grey, a white border and a title banner across the foot. The deck plate
 *    fixes that, and every shot of a card says it again — otherwise seven cards
 *    come back in seven styles and the trick of the seventy-ninth is lost,
 *    because the audience cannot tell what is odd about it.
 *
 * 3. ⚠️ THE OTHER IS THE ONE CARD THAT DOES NOT MATCH. Black ground where the
 *    rest are cream, and the only card whose picture CHANGES — two children at
 *    the start, three at the end. Both states are drawn in the deck's own style,
 *    so what is wrong with it is the colour and the subject, never the drawing.
 *
 * 4. ⚠️ THE EMPTY CHAIR IS EMPTY. It is in a dozen shots and it is the thing the
 *    reader keeps looking at. The frame holds a chair, a table edge and the wall
 *    behind — no figure, no shadow of one, no dent in the seat. What unsettles
 *    is that somebody keeps looking at it.
 *
 * 5. ⚠️ MODERN BURMA, ORDINARY ROOMS. A small rented flat with a plastic chair
 *    and a strip light, a phone with a cracked case, a mother's kitchen. The
 *    only two places that are not ordinary are the dream road and the old house,
 *    and they are not ordinary because they are empty.
 */

