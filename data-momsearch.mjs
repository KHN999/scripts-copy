/**
 * အမေ ချန်ထားတဲ့နေရာ — THE PLACE MY MOTHER KEPT.
 *
 * A village in central Myanmar. The narrator is sixteen, living with his
 * father, his mother and his little sister. His mother is an ordinary woman —
 * she believes in the nats but she is not the kind who goes running to a
 * medium. Then her behaviour changes. She sits up in the night and stares at
 * the front of the house because somebody is standing out there. She lays five
 * plates for dinner when there are four of them. She wakes her son at two in
 * the morning to ask whether his father has come home yet, and when he says
 * his father is asleep in the next room, she shakes her head: that isn't him.
 *
 * The doctor says it is stress and lost sleep. The medium, Daw Hla, asks her
 * almost nothing — only whether she feels there is one extra person in the
 * house at night, and whether she has been keeping a place for him. Then she
 * asks the father whether anything in the house has been MOVED recently, and
 * the boy remembers: a fortnight ago his father brought an old wooden chair
 * back from his grandmother's house. Daw Hla stands straight up. Tonight, let
 * nobody sit in that chair.
 *
 * ⚠️ WHAT THE STORY IS ABOUT. The chair goes into the back storeroom and two
 * nights pass. On the third, in heavy rain, the boy crosses the front room and
 * a man is sitting exactly where the chair used to stand. From the kitchen his
 * mother's voice says: don't wake your father, he's only just got home — while
 * his father is asleep and his mother is asleep. She is standing in the
 * kitchen looking past him at the man, and she says, completely ordinarily,
 * "father, come and eat." The man turns his head, and it is the boy's
 * grandfather, dead seven years, in the clothes he died in. The chair in the
 * locked storeroom has rainwater standing on both armrests.
 *
 * And what the boy cannot forget is not the ghost. It is that his mother had
 * been laying an extra plate for his grandfather every single day, long before
 * the medium asked her anything, and nobody else in the house knew.
 *
 * ──────────────────────────────────────────────────────────────────────────
 *
 * FIVE RULES THIS BOARD IS BUILT ON.
 *
 * 1. ⚠️ THE GRANDFATHER IS BUILT AS AN ORDINARY LIVING OLD MAN. He is not a
 *    corpse, not grey, not damaged and not frightening. He sat in that chair
 *    every night for years and the picture must agree. ⚠️ THE FEAR IS ENTIRELY
 *    POSITIONAL — it is that he is there at all, and that the clothes are the
 *    ones he was buried in.
 *
 * 2. ⚠️ HIS FACE IS WITHHELD UNTIL SHOT 30. Before that he is a seated shape
 *    in an unlit room, facing away, with no feature resolving. The whole story
 *    turns on one recognition and a plate attaches to every prompt, so the
 *    reveal is rationed to the shot that earns it.
 *
 * 3. ⚠️ THE CHAIR IS A CHARACTER AND MUST BE THE SAME OBJECT EVERY TIME. Dark
 *    hardwood, a worn seat, one armrest rubbed pale, a repaired back rail. It
 *    carries the whole film and a chair that changes shape costs it the spine.
 *
 * 4. ⚠️ THE FIFTH PLATE IS THE REAL SUBJECT AND IT IS SHOWN THREE TIMES —
 *    once as a mistake, once as a habit, and once at the end as the thing she
 *    had been doing all along. Count them in frame: four, then five.
 *
 * 5. ⚠️ NOBODY IS EVER SHOWN DEAD AND NOTHING IS EVER DAMAGED. There is no
 *    violence anywhere in this story. The most frightening frame in it is a
 *    woman standing in a kitchen saying something completely ordinary.
 */

