/**
 * ပုဂံသူရဲ့ နောက်ဆုံးဆုတောင်း — THE LAST PRAYER OF THE BAGAN WOMAN.
 *
 * Kaung Set is twenty-nine and photographs old buildings for a living in
 * Mandalay. In November he goes to Bagan alone. On his second day he finds a
 * small red-brick temple nobody visits, and an old man sitting outside tells
 * him the villagers call it Me Hnin's temple, after an ancient woman who died
 * in it — and not to go inside near sunset, because that is when she waits for
 * her man.
 *
 * At five he is photographing the temple when a woman in Bagan-period dress
 * appears in the doorway. He takes her for a costumed model and asks for one
 * frame. She smiles. He lowers the camera and she is gone — but she is in the
 * photograph, holding a small bronze plaque, and when he zooms in, the worn
 * lettering on it reads his own name.
 *
 * That night she knocks at his hotel door. Her hand is ice. The corridor goes
 * dark, and when the light comes back she has gone and the plaque is in his
 * hand. An antiquarian reads it for him: a vow between Me Hnin and Kaung Set,
 * and underneath — let us meet again in the next life. The old man finishes the
 * story: Me Hnin offered flowers at this temple, her lover was a soldier, he
 * marched out and never came back, and she waited years and died here. ⚠️ AND
 * IF SHE EVER FINDS HIM, SHE WILL NEVER LET HIM GO AGAIN.
 *
 * At midnight she comes for him, and takes him to the day they first met: an
 * eleventh-century street, horse carts, pagodas going up. A young soldier walks
 * past him towards her — ⚠️ WITH HIS OWN FACE. The soldier gives her the
 * plaque and promises to marry her when he comes back. Then the street becomes
 * a battlefield, and the soldier is on the ground with an arrow in him, saying
 * he cannot come back after all.
 *
 * ⚠️ WHAT THE STORY IS ABOUT. She will not release him. He does not fight her:
 * he tells her the man loved her, that the truth of it does not depend on her
 * going on waiting, and that she has spent her own life on a vigil. She lets go
 * of his hand, says she is tired, and stops waiting. He wakes at dawn in the
 * hotel with the plaque wiped smooth but for one line — released from waiting.
 *
 * ⚠️ THE LAST TURN. He goes back, offers flowers, and she waves him off from
 * the doorway with no sadness left in her face. That night his camera holds a
 * photograph he never took: Me Hnin hand in hand with a Bagan soldier, both
 * smiling — ⚠️ AND THE SOLDIER'S FACE IS NOT HIS. She never mistook him for her
 * lover. She used him to find the way back to the man himself.
 *
 * ──────────────────────────────────────────────────────────────────────────
 *
 * SIX RULES THIS BOARD IS BUILT ON.
 *
 * 1. ⚠️ ME HNIN IS BUILT AS AN ORDINARY LIVING YOUNG WOMAN AND THE FILM LOVES
 *    HER. Warm skin, clear eyes, good colour, a real smile. The fear is where
 *    she is and what she says, never how she looks. ⚠️ THE TWO SHOTS WHERE SHE
 *    TURNS ARE GRADED IN THE SHOT AND NEVER IN THE PLATE — a frightening plate
 *    attaches to every frame she is in and wrecks an ending that is a kindness.
 *
 * 2. ⚠️ NO PLATE CARRIES THE ENDING. Her plate is a Bagan flower girl and says
 *    nothing about dying, waiting, or whose face anybody has. A plate rides on
 *    every later prompt, so a secret written into one is a secret spoiled in
 *    shot 1.
 *
 * 3. ⚠️ THE SOLDIER HAS KAUNG SET'S FACE IN THE VISION AND NOT IN THE LAST
 *    PHOTOGRAPH. The စစ်သား plate IS the vision soldier and says so plainly —
 *    that is the midpoint, not the twist. ⚠️ THE SOLDIER IN THE FINAL
 *    PHOTOGRAPH IS WRITTEN INLINE, IS A PLAINLY DIFFERENT MAN, AND NEVER GETS
 *    THAT PLATE ATTACHED.
 *
 * 4. ⚠️ NO PICTURE IS EVER ASKED TO SPELL A WORD. The plaque carries worn
 *    incised lettering and nothing more; what it says is carried by the
 *    narration and the caption. Asking the image for Burmese words returns
 *    shapes that are not Burmese, in a shot whose whole point is a name.
 *
 * 5. ⚠️ THE ARROW IS A SHAFT, NOT A WOUND. On the battlefield the frame holds
 *    the shaft standing against his chest and his own hand closed round it, his
 *    clothing whole and unstained. The narration says what it is. The picture
 *    does not open him.
 *
 * 6. ⚠️ ORDINARY BAGAN, NOT A TOURIST POSTER AND NOT A HAUNTED PLACE. Red
 *    brick, dry scrub, dust, a goat track, a plastic chair outside a tea stall.
 *    No balloons, no mist, no candles, no symbols.
 */

